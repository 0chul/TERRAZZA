const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require('../node_modules/typescript');
require('fake-indexeddb/auto');
const out = path.resolve('.work/funds-compiled');
fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(path.join(out,'package.json'),JSON.stringify({type:'commonjs'}));
for(const file of ['types','dates','defaultInteriorCosts','funds','db']) fs.writeFileSync(path.join(out,file+'.js'),ts.transpileModule(fs.readFileSync(file+'.ts','utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText);
const {DEFAULT_INTERIOR_COSTS:rows,DEFAULT_INTERIOR_DEPOSITS:deposits} = require(path.join(out,'defaultInteriorCosts.js'));
const {summarizeFunds,expensePayer,expenseScope,companyOutflow,validateFundExpense,fundsCsvCell} = require(path.join(out,'funds.js'));
const {dbService,initDB} = require(path.join(out,'db.js'));
(async()=>{
  const summary=summarizeFunds(rows,deposits);
  assert.equal(summary.received,16110000);
  assert.equal(summary.companyDirect,15137450);
  assert.equal(summary.personal,269500);
  assert.equal(summary.customerDirect,389500);
  assert.equal(summary.balance,972550);
  assert.equal(summary.projectActual,15796450);
  assert.equal(summary.settlementUnknown,269500);
  assert.equal(summary.personalUnsettled,0);
  assert.equal(summary.matrix.find(r=>r.scope==='construction').total,14724950);
  assert.equal(summary.matrix.reduce((s,r)=>s+r.total,0),summary.projectActual);
  for(const entry of summary.matrix) assert.equal(Object.values(entry.payers).reduce((s,n)=>s+n,0),entry.total);
  const reimbursed=rows.map(row=>expensePayer(row)==='personal'?{...row,reimbursedAmount:row.cost,settlementConfirmed:true}:row);
  const settled=summarizeFunds(reimbursed,deposits);
  assert.equal(settled.companyExecuted,15406950);
  assert.equal(settled.balance,703050);
  assert.equal(settled.projectActual,summary.projectActual);
  assert.equal(settled.settlementUnknown,0);
  assert.equal(reimbursed.reduce((sum,row)=>sum+companyOutflow(row),0),settled.companyExecuted);
  assert.equal(fundsCsvCell('=1+1'), '"\'=1+1"');
  assert.equal(fundsCsvCell('  =1+1'), '"\'  =1+1"');
  assert.equal(fundsCsvCell(1000), '"1000"');
  const personal=rows.find(row=>expensePayer(row)==='personal');
  const partial=rows.map(row=>row.id===personal.id?{...row,reimbursedAmount:5000,settlementConfirmed:true}:row);
  assert.equal(summarizeFunds(partial,deposits).companyExecuted,15142450);
  assert.equal(summarizeFunds(partial,deposits).projectActual,15796450);
  assert.equal(summarizeFunds(partial,deposits).personalUnsettled,personal.cost-5000);
  const excluded=rows.map((row,index)=>index===0?{...row,scope:'excluded'}:row);
  assert.equal(summarizeFunds(excluded,deposits).companyExecuted,15137450);
  assert.equal(summarizeFunds(excluded,deposits).projectActual,15796450-rows[0].cost);
  const planned={id:'plan',date:'2999-01-01',item:'예상공사',category:'도장',cost:100000,payer:'company',estimated:true};
  assert.equal(summarizeFunds([...rows,planned],deposits).companyExecuted,15137450);
  assert.equal(summarizeFunds([...rows,planned],deposits).projectActual,15796450);
  assert.equal(summarizeFunds([...rows,planned],deposits).planned,100000);
  const unknown={id:'unknown',date:'2026-10-13',item:'분류대기',category:'미정',cost:1000,estimated:false};
  assert.equal(expensePayer(unknown),'unclassified');
  assert.equal(expenseScope(unknown),'unclassified');
  assert.equal(summarizeFunds([...rows,unknown],deposits).unknownPayer,1000);
  assert.equal(expensePayer({...rows.find(r=>r.payment==='직접구매'),payer:'personal'}),'personal');
  assert(validateFundExpense({...personal,payer:'personal',reimbursedAmount:personal.cost+1}));
  assert(validateFundExpense({...personal,payer:'company',reimbursedAmount:1}));
  assert(validateFundExpense({...personal,payer:'personal',estimated:true,reimbursedAmount:1}));
  assert.equal(validateFundExpense({...personal,payer:'personal',reimbursedAmount:5000,reimbursementDate:'',settlementConfirmed:true}),'');
  assert(validateFundExpense({...personal,payer:'personal',reimbursedAmount:5000,reimbursementDate:'2999-01-01'}));
  await dbService.importFinanceSource();
  const two=rows.slice(0,2).map(row=>({...row,payer:'personal',scope:'equipment'}));
  await dbService.saveInteriorCosts(two);
  const read=await dbService.getAllInteriorCosts();
  assert.equal(read.find(r=>r.id===two[0].id).payer,'personal');
  assert.equal(read.find(r=>r.id===two[1].id).scope,'equipment');
  assert.equal(read.length,53);
  (await initDB()).close();
  console.log('PASS: customer receipts, 4 personal + 4 customer payments, cash reconciliation, two-axis matrix, partial/full reimbursement without double count, exclusions, planned and unknown costs, validation and atomic bulk persistence.');
})().catch(error=>{console.error(error);process.exitCode=1});
